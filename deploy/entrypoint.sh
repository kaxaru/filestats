#!/usr/bin/env bash
# Точка входа контейнера: миграции, затем сервер.
set -euo pipefail

echo "==> применяю миграции"
alembic upgrade head

echo "==> запускаю приложение"
# Один воркер намеренно: внутри процесса живёт фоновая задача скачивания,
# а два параллельных воркера с одного IP гарантированно словят бан на 30 минут.
exec uvicorn app.main:app --host 0.0.0.0 --port 8000 --workers 1 --proxy-headers
