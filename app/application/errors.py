"""Ошибки, пересекающие границу порта каталога.

Объявлены в прикладном слое, а не в инфраструктуре: сценарий должен уметь их
ловить, не зная, что под портом httpx. Иначе зависимость развернулась бы в
обратную сторону — приложение начало бы импортировать инфраструктуру.
"""

from __future__ import annotations


class CatalogError(Exception):
    """Каталог не смог выполнить запрос."""


class CatalogUnavailable(CatalogError):
    """Сеть не отвечает, попытки исчерпаны."""


class CatalogThrottled(CatalogError):
    """Отказы по частоте запросов идут подряд слишком долго.

    Отличается от обычной паузы: пауза — штатное ожидание, а это признак, что
    ждать дальше бессмысленно и прогон надо остановить с внятной причиной.
    """

    def __init__(self, retry_after_seconds: float) -> None:
        super().__init__(f"каталог не выпускает из лимита, ждать ещё {retry_after_seconds:.0f} с")
        self.retry_after_seconds = retry_after_seconds


class FileMissingFromCatalog(CatalogError):
    """Запрошенного имени в каталоге нет."""

    def __init__(self, names: list[str]) -> None:
        super().__init__(f"нет в каталоге: {', '.join(names)}")
        self.names = names


class DownloadStalled(CatalogError):
    """Обход перестал продвигаться.

    Каталог продолжает предлагать имена, но ни скачать, ни подтвердить их не
    получается — например, файл числится в выдаче, но отсутствует физически.
    Без этой проверки цикл крутился бы бесконечно: неподтверждённое имя
    возвращается в выдаче снова и снова. Лучше остановиться и назвать причину.
    """

    def __init__(self, names: list[str]) -> None:
        super().__init__(f"обход не продвигается, застряли на: {', '.join(names)}")
        self.names = names
