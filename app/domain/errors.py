"""Ошибки домена."""


class DomainError(Exception):
    """Нарушение правила предметной области."""


class InvalidTransition(DomainError):
    """Попытка перевести сущность в недопустимое состояние."""


class ContentRequired(DomainError):
    """Подтверждение отметки без сохранённого содержимого.

    Центральный инвариант: отметка на сервере необратима, отмеченное имя больше
    никогда не попадёт в выдачу. Подтвердить файл, содержимого которого у нас
    нет, — значит потерять его навсегда.
    """
